#!/usr/bin/env node
/**
 * Codegen: scan lib/openclaw/services/ for `*.plugin.ts` files and write a
 * generated barrel that imports each one for its registration side effect.
 *
 * Why codegen instead of a hardcoded import list or runtime fs-scan:
 *   - A deployment may ship only a subset of plugin files; private or
 *     customer-specific add-ons can exist only on a downstream branch's
 *     working tree. A hardcoded `import "./some-private.plugin"` in tracked
 *     code would break `next build` wherever that file is absent (module not
 *     found).
 *   - A runtime fs-scan + dynamic import is fragile under Next's bundler.
 *   - Build-time codegen resolves the set deterministically from whatever
 *     plugin files are actually present, and the generated file is a plain
 *     static-import barrel the bundler handles normally.
 *
 * Runs from `predev` / `prebuild`. Output is gitignored.
 */
import { readdirSync, writeFileSync, readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const servicesDir = join(here, "..", "lib", "openclaw", "services");
const outFile = join(servicesDir, "_generated-plugins.ts");

const plugins = readdirSync(servicesDir)
  .filter((f) => f.endsWith(".plugin.ts"))
  .map((f) => f.replace(/\.ts$/, ""))
  .sort();

const body = `// AUTO-GENERATED by scripts/gen-service-plugins.mjs — do not edit.
// Importing this barrel runs each plugin's registerManagedMcpService(...) for
// its side effect. The set is whatever *.plugin.ts files exist at build time,
// so private add-on plugins (present only on the private branch) are included
// where they exist and silently omitted where they aren't.
${plugins.map((p) => `import "./${p}";`).join("\n")}
`;

let prev = "";
try {
  prev = readFileSync(outFile, "utf-8");
} catch {
  /* first run */
}
if (prev !== body) {
  writeFileSync(outFile, body);
}
console.log(
  `[gen-service-plugins] ${plugins.length} plugin(s): ${plugins.map((p) => p.replace(".plugin", "")).join(", ")}`,
);
